def normalize_contract_text(text: str) -> str:
    """把「一整行 + 字面量 \\n」形态的正文还原为真换行。

    保守策略：仅当文本内**不含任何真换行**时才替换，避免误改正文里本就存在的字面量 "\\n"。
    """
    if "\n" in text:
        return text
    return text.replace("\\n", "\n")


